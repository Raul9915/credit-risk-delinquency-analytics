-- Monthly snapshots of previous Home Credit credit cards.
SELECT
    CAST(SK_ID_PREV AS BIGINT) AS SK_ID_PREV,
    CAST(SK_ID_CURR AS BIGINT) AS SK_ID_CURR,
    CAST(MONTHS_BALANCE AS INTEGER) AS MONTHS_BALANCE,
    AMT_BALANCE,
    AMT_CREDIT_LIMIT_ACTUAL,
    AMT_BALANCE / NULLIF(AMT_CREDIT_LIMIT_ACTUAL, 0) AS UTILIZATION,
    SK_DPD,
    SK_DPD_DEF
FROM bronze_credit_card
