-- Installment-level repayment history. DAYS_LATE > 0 means paid after the due date.
SELECT
    CAST(SK_ID_PREV AS BIGINT) AS SK_ID_PREV,
    CAST(SK_ID_CURR AS BIGINT) AS SK_ID_CURR,
    NUM_INSTALMENT_NUMBER,
    DAYS_INSTALMENT,
    DAYS_ENTRY_PAYMENT,
    AMT_INSTALMENT,
    AMT_PAYMENT,
    DAYS_ENTRY_PAYMENT - DAYS_INSTALMENT                  AS DAYS_LATE,
    AMT_PAYMENT / NULLIF(AMT_INSTALMENT, 0)               AS PAYMENT_RATIO
FROM bronze_installments
WHERE DAYS_ENTRY_PAYMENT IS NOT NULL
