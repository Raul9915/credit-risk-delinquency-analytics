-- Previous Home Credit applications. 365243 is a sentinel for "no date" -> NULL.
SELECT
    CAST(SK_ID_PREV AS BIGINT) AS SK_ID_PREV,
    CAST(SK_ID_CURR AS BIGINT) AS SK_ID_CURR,
    NAME_CONTRACT_TYPE,
    NAME_CONTRACT_STATUS,
    AMT_APPLICATION,
    AMT_CREDIT,
    AMT_ANNUITY,
    CNT_PAYMENT,
    DAYS_DECISION,
    NULLIF(DAYS_FIRST_DUE, 365243)  AS DAYS_FIRST_DUE,
    NULLIF(DAYS_LAST_DUE, 365243)   AS DAYS_LAST_DUE,
    NULLIF(DAYS_TERMINATION, 365243) AS DAYS_TERMINATION
FROM bronze_previous_application
